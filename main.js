/* ---------- età di Camilla: cambia ogni 29 novembre ---------- */
function camillaAge() {
  // Compleanno: 29 novembre. Oggi ha 23 anni fino al 29/11 del suo compleanno.
  const birth = new Date(2002, 10, 29); // 29 nov 2002
  const now = new Date();
  let age = now.getFullYear() - birth.getFullYear();
  const m = now.getMonth() - birth.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < birth.getDate())) age--;
  return age;
}
function applyAge() {
  const a = camillaAge();
  const el = document.getElementById("teacher-age");
  if (el) el.textContent = a;
}

/* ---------- contatti: tutto da contatti.json ---------- */
const CONTACTS = {
  whatsapp_numero: "390000000000",
  email: "camilla@example.com",
  wechat_id: "",
  messaggio_default: "Ciao Camilla! Vorrei la prova gratis di 30 min (PROVA GRATIS)"
};

function waLink(msg) {
  return "https://wa.me/" + CONTACTS.whatsapp_numero +
    "?text=" + encodeURIComponent(msg || CONTACTS.messaggio_default);
}

function applyContacts() {
  // tutti i link WhatsApp mantengono il loro messaggio, cambia solo il numero
  document.querySelectorAll('a[href*="wa.me"]').forEach((a) => {
    const old = a.getAttribute("href") || "";
    let msg = CONTACTS.messaggio_default;
    const m = old.match(/[?&]text=([^&]*)/);
    if (m) {
      try { msg = decodeURIComponent(m[1]); } catch (e) { msg = m[1]; }
    }
    a.href = waLink(msg);
  });
  // email
  document.querySelectorAll('a[href^="mailto:"]').forEach((a) => {
    const old = a.getAttribute("href") || "";
    const q = old.includes("?") ? old.slice(old.indexOf("?")) : "";
    a.href = "mailto:" + CONTACTS.email + q;
  });
  // WeChat ID visibile
  document.querySelectorAll("[data-wechat-id]").forEach((el) => {
    el.textContent = CONTACTS.wechat_id || "ID su richiesta";
  });
  // numero visibile (es. "scrivimi al ...")
  document.querySelectorAll("[data-tel-visibile]").forEach((el) => {
    el.textContent = CONTACTS.telefono_visibile || "";
  });
}

async function loadContacts() {
  try {
    const r = await fetch("contatti.json", { cache: "no-store" });
    if (r.ok) Object.assign(CONTACTS, await r.json());
  } catch (e) { /* fallback ai valori sopra */ }
  applyContacts();
}

/* ---------- lingua ---------- */
function setLanguage(l) {
  lang = l;
  const dict = I18N[l];
  const age = camillaAge();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (dict[k] !== undefined) el.innerHTML = dict[k].replace(/\{\{age\}\}/g, age);
  });
  document.getElementById("btn-it").classList.toggle("active", l === "it");
  document.getElementById("btn-zh").classList.toggle("active", l === "zh");
  document.documentElement.lang = l === "zh" ? "zh-CN" : "it";
}

document.getElementById("btn-it").addEventListener("click", () => setLanguage("it"));
document.getElementById("btn-zh").addEventListener("click", () => setLanguage("zh"));

/* ---------- disponibilità ---------- */
async function loadCal() {
  const box = document.getElementById("cal-box");
  try {
    const r = await fetch("disponibilita.json", { cache: "no-store" });
    const d = await r.json();
    const zhDay = { Sabato: "周六", Domenica: "周日" };
    box.innerHTML = "";
    d.slots.forEach((s) => {
      const div = document.createElement("div");
      div.className = "day-box";
      const slots = s.ore.length
        ? s.ore.map((o) =>
            `<a class="slot" target="_blank" rel="noopener" href="${waLink(
              `Ciao Camilla! Vorrei prenotare ${s.giorno} ore ${o}`
            )}">${o}</a>`).join("")
        : `<span class="slot off">completo 满</span>`;
      div.innerHTML = `<h3>${s.giorno} <span class="zh-inline">${zhDay[s.giorno] || ""}</span></h3><div class="slots">${slots}</div>`;
      box.appendChild(div);
    });
    document.getElementById("aggiornato").textContent =
      (lang === "zh" ? "更新： " : "Aggiornato: ") + d.ultimo_aggiornamento;
    document.getElementById("promo-line").textContent = d.annuncio || "";
  } catch (e) {
    box.innerHTML =
      '<div class="day-box"><h3>Sabato <span class="zh-inline">周六</span></h3><div class="slots"><span class="slot">09:00</span><span class="slot">11:00</span><span class="slot">15:00</span></div></div><div class="day-box"><h3>Domenica <span class="zh-inline">周日</span></h3><div class="slots"><span class="slot">10:00</span><span class="slot">16:00</span></div></div>';
  }
}

/* ---------- reveal on scroll ---------- */
const io = new IntersectionObserver(
  (entries) => entries.forEach((e) => e.isIntersecting && e.target.classList.add("visible")),
  { threshold: 0.08 }
);
document.querySelectorAll(".reveal").forEach((el) => io.observe(el));

/* ---------- avvio: prima i contatti, poi il calendario ---------- */
loadContacts().then(() => { applyAge(); setLanguage(lang); loadCal(); });
